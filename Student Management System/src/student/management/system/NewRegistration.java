    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        String idText = txtID.getText().trim();
        String name = txtName.getText().trim();
        String contact = txtContact.getText().trim();
        String division = cmbDivision.getSelectedItem().toString();
        String address = txtAddress.getText().trim();
        if (idText.isEmpty() || name.isEmpty() || contact.isEmpty() || address.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields");
            return;
        }
        try {
            int id = Integer.parseInt(idText);
            Connection con = DBConnect.dbCon();
            String sql = "INSERT INTO student (id, name, contact, division, address) "
                       + "VALUES (?, ?, ?, ?, ?)";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setInt(1, id);
            pst.setString(2, name);
            pst.setString(3, contact);
            pst.setString(4, division);
            pst.setString(5, address);
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Student Registered Successfully");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID must be a number");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnRegisterActionPerformed

