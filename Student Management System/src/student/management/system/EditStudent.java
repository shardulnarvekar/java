    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        String idText = cmbID.getSelectedItem().toString().trim();
        String name = txtName.getText().trim();
        String contact = txtContact.getText().trim();
        String division = cmbDivision.getSelectedItem().toString();
        String address = txtAddress.getText().trim();
        if (idText.isEmpty() || name.isEmpty() || contact.isEmpty() || address.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields");
            return;
        }
        try {
            int id = Integer.parseInt(idText);
            Connection con = DBConnect.dbCon();
            String sql = "UPDATE student SET name = ?, contact = ?, division = ?, address = ? "
                       + "WHERE id = ?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, name);
            pst.setString(2, contact);
            pst.setString(3, division);
            pst.setString(4, address);
            pst.setInt(5, id);
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Student Updated Successfully");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID must be a number");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String idText = cmbID.getSelectedItem().toString().trim();
        if (idText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter or select an ID");
            return;
        }
        try {
            int id = Integer.parseInt(idText);
            Connection con = DBConnect.dbCon();
            String sql = "SELECT * FROM student WHERE id = ?";
            PreparedStatement pst = con.prepareStatement(sql);
            pst.setInt(1, id);
            ResultSet rs = pst.executeQuery();
            if (rs.next()) {
                txtName.setText(rs.getString("name"));
                txtContact.setText(rs.getString("contact"));
                cmbDivision.setSelectedItem(rs.getString("division"));
                txtAddress.setText(rs.getString("address"));
            } else {
                JOptionPane.showMessageDialog(this, "Student not found");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "ID must be a number");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnSearchActionPerformed

