    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        String idText = txtID.getText().trim();
        String name = txtName.getText().trim();
        String department = cmbDepartment.getSelectedItem().toString();
        String designation = cmbDesignation.getSelectedItem().toString();
        String salaryText = txtSalary.getText().trim();
        String contact = txtContact.getText().trim();
        String email = txtEmail.getText().trim();
        String address = txtAddress.getText().trim();

        if (idText.isEmpty() || name.isEmpty() || salaryText.isEmpty()
                || contact.isEmpty() || email.isEmpty() || address.isEmpty()) {

            JOptionPane.showMessageDialog(this, "Please fill all fields");
            return;
        }

        if (!contact.matches("\\d{10}")) {

            JOptionPane.showMessageDialog(this, "Contact must be exactly 10 digits");
            return;
        }

        try {

            int id = Integer.parseInt(idText);
            double salary = Double.parseDouble(salaryText);

            EmployeeOperations emp = new EmployeeOperations(
                id,
                name,
                department,
                designation,
                salary,
                contact,
                email,
                address
            );

            emp.updateEmployee();

            JOptionPane.showMessageDialog(this, "Employee Updated Successfully");

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this, "ID and Salary must be numeric");

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnSaveActionPerformed

