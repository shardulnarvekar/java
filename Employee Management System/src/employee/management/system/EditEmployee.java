    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        String idText = txtID.getText().trim();

        if (idText.isEmpty()) {

            JOptionPane.showMessageDialog(this, "Please enter Employee ID");
            return;
        }

        try {

            int id = Integer.parseInt(idText);

            EmployeeOperations emp = EmployeeOperations.searchEmployee(id);

            if (emp != null) {

                txtName.setText(emp.name);
                cmbDepartment.setSelectedItem(emp.department);
                cmbDesignation.setSelectedItem(emp.designation);
                txtSalary.setText(String.valueOf(emp.salary));
                txtContact.setText(emp.contact);
                txtEmail.setText(emp.email);
                txtAddress.setText(emp.address);

            } else {

                JOptionPane.showMessageDialog(this, "Employee not found");

            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this, "ID must be a number");

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnSearchActionPerformed

