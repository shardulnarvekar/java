    public int validate(String sid, String scontact, String sname)
{
    if(sid.isEmpty())
        return 0;

    if(sname.isEmpty())
        return 0;

    if(scontact.length() != 10)
        return 0;

    return 1;
}
    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        if(validate(sid.getText(), scontact.getText(), sname.getText()) == 0)
{
    JOptionPane.showMessageDialog(this, "Invalid Data");
    return;
}

    String str = "insert into students values(?,?,?,?,?)";

    DBConnect d = new DBConnect();

    java.sql.Connection con = d.dbCon();

    try{

        PreparedStatement ps = con.prepareStatement(str);

        ps.setInt(1, Integer.parseInt(sid.getText().trim()));

        ps.setString(2, sname.getText().trim());

        ps.setString(3, sdiv.getSelectedItem().toString());

        ps.setString(4, scontact.getText().trim());

        ps.setString(5, saddress.getText().trim());

int k = ps.executeUpdate();

        if(k>0)
        {
            javax.swing.JOptionPane.showMessageDialog(this,"New Record Added");
        }

    }

    catch(Exception e)
    {
        javax.swing.JOptionPane.showMessageDialog(this,e);
    }
    }//GEN-LAST:event_btnSaveActionPerformed

