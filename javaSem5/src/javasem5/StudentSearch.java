    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        DBConnect db = new DBConnect();

    try{

        Connection con = db.dbCon();

        String str = "SELECT * FROM students WHERE sid=?";

        PreparedStatement ps = con.prepareStatement(str);

        ps.setInt(1,
            Integer.parseInt(sid.getSelectedItem().toString()));

        ResultSet rs = ps.executeQuery();

        if(rs.next())
        {
            sname.setText(rs.getString("sname"));

            scontact.setText(rs.getString("scontact"));

            sbatch.setText(rs.getString("sdiv"));

            saddress.setText(rs.getString("saddress"));
        }

        else
        {
            JOptionPane.showMessageDialog(this,"Record Not Found");
        }

        rs.close();
        ps.close();
        con.close();

    }

    catch(Exception e)
    {
        JOptionPane.showMessageDialog(this,e);
    }
    }//GEN-LAST:event_btnSearchActionPerformed

